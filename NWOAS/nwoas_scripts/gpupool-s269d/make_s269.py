#!/usr/bin/env python3
"""S269 (daily stack + GPU pool window): generate agxdcp-s269-guest-test.sh from agxdcp-s268-guest-test.sh and
bt-s268/run-s269.sh from bt-s268/run-s268.sh.  Host only.  Every replaced anchor must appear exactly once.
  python3 -I gpupool-s269d/make_s269.py           (refuses to overwrite an existing output unless --force)
Pool facts (port-j274/gpu/driver-p15/RESULT-POOL-S265.md, RESULT-2775.md ch.36, agxdcp-s265-guest-test.sh):
the only launcher change is NWOAS_AGX_POOL_IPA=0xd00000000 (4 GiB fixed); no HV / payload / ACPI / driver change."""
import hashlib, sys
from pathlib import Path
S = Path('/Users/angigyeom/Desktop/DEV/NWOAS/nwoas_scripts')
force = '--force' in sys.argv

def sub(t, old, new):
    assert t.count(old) == 1, ('anchor not exactly once', old[:90], t.count(old))
    return t.replace(old, new, 1)

# ---------------- launcher
src = (S / 'agxdcp-s268-guest-test.sh').read_text()
t = sub(src, '#!/bin/bash\n', '''#!/bin/bash
# S269: agxdcp-s268-guest-test.sh (sha256 %s, generated by gpupool-s269d/make_s269.py)
# with ONE change: the 4 GiB AGX pool window (segment 3, demand-backed Windows memory) at IPA 0xd00000000, as in
# agxdcp-s265-guest-test.sh.  NWOAS_S269_POOL=1 (default; NWOAS_POOL is accepted as the same switch) / 0 = pool off
# = S268 exactly (NWOAS_AGX_POOL_IPA=0).  No HV, payload, ACPI or driver change (RESULT-POOL-S265.md, RESULT-2775.md
# ch.36).  Driver installs keep using a pool-off boot.  Wrapper bt-s268/run-s269.sh ("S269 DONE").
# HARDWARE-UNVERIFIED: the pool has only run with g254L + the S259 payload (S265 chains), never with Bluetooth,
# the S260 power defaults, NVMe QD 32, the S280 payload or g262U.
''' % hashlib.sha256(src.encode()).hexdigest())
t = sub(t, 'export NWOAS_AGX_SCANOUT_INTID=889 NWOAS_AGX_POOL_IPA=0\n', '''# S269: pool window on unless NWOAS_S269_POOL=0 (then exactly the S268 value 0).
S269_POOL="${NWOAS_S269_POOL:-${NWOAS_POOL:-1}}"
case "$S269_POOL" in
    1) S269_POOL_IPA=0xd00000000 ;;
    0) S269_POOL_IPA=0 ;;
    *) echo 'STOP: NWOAS_S269_POOL must be 0 or 1'; exit 1 ;;
esac
export NWOAS_S269_POOL="$S269_POOL"
export NWOAS_AGX_SCANOUT_INTID=889 NWOAS_AGX_POOL_IPA=$S269_POOL_IPA
''')
anchor = 'echo "[S262] NWOAS_S262_HV='
i = t.index(anchor); assert t.count(anchor) == 1
t = t[:i] + 'echo "[S269] NWOAS_S269_POOL=$NWOAS_S269_POOL NWOAS_AGX_POOL_IPA=$NWOAS_AGX_POOL_IPA (4 GiB pool window when on)" | tee -a "$LOG"\n' + t[i:]
L_OUT = S / 'agxdcp-s269-guest-test.sh'

# ---------------- wrapper
w = (S / 'bt-s268/run-s268.sh').read_text()
wsha = hashlib.sha256(w.encode()).hexdigest()
w = sub(w, '#!/bin/bash\n', '''#!/bin/bash
# S269: bt-s268/run-s268.sh (sha256 %s, generated by gpupool-s269d/make_s269.py) with the launcher
# agxdcp-s269-guest-test.sh (S268 + GPU pool window, NWOAS_S269_POOL=1 default, 0 = S268), the result file
# run-s269-*.txt and the last line "S269 DONE ... pool=<0|1>".  Added from gpupool-s265/boot-s265.sh: on a W4 restart
# the previous boot's HV console is checked for EL2 exceptions (the shutdown of a pool-on boot is the KMD stop path
# through the pool window); after the worker connects the HV AGX lines + "pool armed=<0|1>" judgement are printed;
# every job wait also stops on an EL2 exception or LAUNCHER EXIT; EL2 exception count after D28 and at the end.
''' % wsha)
w = sub(w, 'RES=$ROOT/bt-s268/runs/run-s268-$(date "+%Y%m%d-%H%M%S").txt', 'RES=$ROOT/bt-s268/runs/run-s269-$(date "+%Y%m%d-%H%M%S").txt')
w = sub(w, '''jobwait() { local L=$1 j; j=$(python3 -I -c "import json,sys;print(json.load(open(sys.argv[1]))['id'])" $L/job.json)
  for i in $(seq 1 480); do grep -q "\\"job\\": $j, \\"kind\\": 3" $L/events.jsonl && break; sleep 5; done''',
'''hvdead() { grep -a -q -E 'Exception taken from EL2|Unhandled exception' "$LOG.vuart" 2>/dev/null || grep -q "LAUNCHER EXIT" $CUR; }
jobwait() { local L=$1 j; j=$(python3 -I -c "import json,sys;print(json.load(open(sys.argv[1]))['id'])" $L/job.json)
  for i in $(seq 1 480); do grep -q "\\"job\\": $j, \\"kind\\": 3" $L/events.jsonl && break
    hvdead && { say "ABORT hypervisor/launcher gone during job $j"; grep -a -n -B3 -A12 'Exception taken from EL2' "$LOG.vuart" | head -40 | tee -a $RES; tail -5 $CUR | tee -a $RES; exit 7; }
    sleep 5; done''')
w = sub(w, 'say "START old=$OLDLINK ', 'say "START S269 NWOAS_S269_POOL=${NWOAS_S269_POOL:-${NWOAS_POOL:-1}} old=$OLDLINK ')
w = sub(w, '''  grep -q "LAUNCHER EXIT" $OLDOUT || { say "ABORT: old launcher did not exit"; exit 4; }
  say "old launcher exited"''', '''  grep -q "LAUNCHER EXIT" $OLDOUT || { say "ABORT: old launcher did not exit"; exit 4; }
  OLDLOG=$(sed -n "s/^Log: //p" $OLDOUT | head -1)
  # the shutdown of a pool-on boot is the KMD stop path too (gpupool-s265/boot-s265.sh)
  if [ -n "$OLDLOG" ] && grep -a -q -E 'Exception taken from EL2|Unhandled exception' "$OLDLOG.vuart" 2>/dev/null; then
    say "OLD BOOT HV EXCEPTION at shutdown (see $OLDLOG.vuart)"; grep -a -n -B3 -A12 'Exception taken from EL2' "$OLDLOG.vuart" | head -40 | tee -a $RES
  else say "old launcher exited, no EL2 exception in its HV console"; fi''')
w = sub(w, 'CUR=$ROOT/logs/launcher-agxdcp268-bt-$(date "+%Y%m%d-%H%M%S").out', 'CUR=$ROOT/logs/launcher-agxdcp269-pool-$(date "+%Y%m%d-%H%M%S").out')
w = sub(w, 'caffeinate -dims bash $ROOT/agxdcp-s268-guest-test.sh > $CUR', 'caffeinate -dims bash $ROOT/agxdcp-s269-guest-test.sh > $CUR')
w = sub(w, 'say "worker connected link=$L"\n', '''say "worker connected link=$L"
say "hypervisor AGX lines:"; grep -a -E 'NWOAS-AGX: (pool window|GPU broker table|MEDIATE armed|install REFUSED|local reserve)' "$LOG.vuart" | head -12 | tee -a $RES
POOL=0; grep -a -q 'MEDIATE armed: .* pool=1 ' "$LOG.vuart" && grep -a -q 'pool window v1 IPA=0xd00000000 bytes=0x100000000' "$LOG.vuart" && POOL=1
say "pool armed=$POOL"
''')
w = sub(w, 'runjob $ROOT/agx-s248/jobs/D28-rearm.cmd > /dev/null; say "D28 done"', 'runjob $ROOT/agx-s248/jobs/D28-rearm.cmd > /dev/null; say "D28 done; HV EL2 exceptions so far: $(grep -a -c \'Exception taken from EL2\' "$LOG.vuart")"')
w = sub(w, 'say "S268 DONE link=$L out=$CUR log=$LOG"', 'say "S269 DONE link=$L out=$CUR log=$LOG pool=$POOL el2_exc=$(grep -a -c \'Exception taken from EL2\' "$LOG.vuart")"')
W_OUT = S / 'bt-s268/run-s269.sh'

for p, txt in ((L_OUT, t), (W_OUT, w)):
    if p.exists() and not force and p.read_text() != txt:
        raise SystemExit('refuse to overwrite %s (use --force)' % p)
    p.write_text(txt); p.chmod(0o755)
    print('wrote', p, hashlib.sha256(txt.encode()).hexdigest())
